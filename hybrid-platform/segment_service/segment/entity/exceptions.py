"""segment/entity/exceptions.py — доменные ошибки независимого ядра.

Ядро (слой Entities) сигнализирует о нарушении инвариантов синаптического
профиля через явные доменные исключения. Согласно подразделу 3.2.3, некорректное
состояние выявляется в точке возникновения (фаза инициализации профиля), а не
откладывается до горячего пути обработки запроса.

Модуль не импортирует ничего, кроме стандартной библиотеки: это требование
правила зависимостей (подраздел 3.5.1) — ядро не зависит от внешних слоёв.
"""


class CoreError(Exception):
    """Базовый класс доменных ошибок ядра."""


class DimensionMismatchError(CoreError):
    """Размерность входного представления не совпадает с размерностью профиля d
    (выражение 2.22)."""


class SingularCovarianceError(CoreError):
    """Ковариационная матрица Σk вырождена и не допускает обращения, либо
    обращённая матрица Σk⁻¹ не положительно определена (квадратичная форма
    расстояния Махаланобиса отрицательна). Диагностируется при построении
    профиля или при вычислении метрики (подраздел 3.5.3)."""


class ProfileNotPositiveDefiniteError(CoreError):
    """Σk⁻¹ потеряла положительную определённость — нарушение инварианта
    профиля (выражение 2.28)."""